#!/usr/bin/env node
/** Writes apps/web/src/generated/catalog.ts from packages/catalog/src/data.json. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(root, "packages/catalog/src/data.json");
const outDir = path.join(root, "apps/web/src/generated");
const outPath = path.join(outDir, "catalog.ts");

const data = JSON.parse(fs.readFileSync(dataPath, "utf8"));
const json = JSON.stringify(data, null, 2);

const body = `/** Generated by \`pnpm catalog:generate\` from packages/catalog/src/data.json. Do not edit. */

export type CatalogTier = "free" | "paid";

export type DemoField = "query" | "place" | "code" | "symbols";

export type CatalogTool = {
  name: string;
  description: string;
};

export type CatalogDemo = {
  id: string;
  label: string;
  tool: string;
  field?: DemoField;
  placeholder?: string;
  value: string;
  input: Record<string, unknown>;
};

export type CatalogSource = {
  id: string;
  title: string;
  tier: CatalogTier;
  package: string;
  hosts: string[];
  note: string;
  tools: CatalogTool[];
  demo: CatalogDemo | null;
};

type CatalogFile = {
  profiles: Record<string, string[]>;
  sources: CatalogSource[];
};

const data = ${json} as CatalogFile;

export const CATALOG_SOURCES: CatalogSource[] = data.sources;

export const FREE_TIER_SOURCE_IDS = CATALOG_SOURCES.filter((s) => s.tier === "free").map((s) => s.id);

export const PAID_ONLY_SOURCE_IDS = CATALOG_SOURCES.filter((s) => s.tier === "paid").map((s) => s.id);

export const TRUST_TIER_SOURCE_IDS = CATALOG_SOURCES.map((s) => s.id);

export const SOURCE_PROFILES: Record<string, string[]> = {
  default: [...FREE_TIER_SOURCE_IDS],
  trust: [...TRUST_TIER_SOURCE_IDS],
  ...data.profiles,
};

export const DEMO_PRESETS: CatalogDemo[] = CATALOG_SOURCES.flatMap((s) => (s.demo ? [s.demo] : []));

export const DEMO_TOOL_NAMES = DEMO_PRESETS.map((p) => p.tool);

export function getCatalogSource(id: string): CatalogSource | undefined {
  return CATALOG_SOURCES.find((s) => s.id === id);
}
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outPath, body);
console.log(`wrote ${path.relative(root, outPath)}`);
